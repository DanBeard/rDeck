void test_compressed_advertisement_accepted(void) {
    // Build advertisement with compressed flag set (bit 1)
    // flags = 0x03 (encrypted + compressed)
    JsonDocument doc;
    doc["t"] = 100;
    doc["d"] = 200;  // decompressed size > transfer size
    doc["n"] = 1;
    doc["h"] = MsgPackBinary(resource_hash_bytes, 32);
    doc["r"] = MsgPackBinary(random_hash_bytes, 4);
    doc["o"] = MsgPackBinary(resource_hash_bytes, 32);
    doc["i"] = 1;
    doc["l"] = 1;
    doc["q"] = nullptr;
    doc["f"] = 0x03;  // encrypted + compressed
    doc["m"] = MsgPackBinary(map_hash_part0, 4);

    uint8_t buffer[256];
    size_t len = serializeMsgPack(doc, buffer, sizeof(buffer));
    Bytes packed(buffer, len);

    ResourceAdvertisement adv = ResourceAdvertisement::unpack(packed);
    TEST_ASSERT_TRUE(adv.c);   // compressed flag is set
    TEST_ASSERT_TRUE(adv.e);   // encrypted flag is set

    // With RET_BZ2_SUPPORT defined, the compressed flag should NOT cause
    // Resource::accept() to reject the advertisement. We can't call accept()
    // directly (needs a real Packet/Link), but we verify the flag is preserved
    // through pack/unpack, which is what accept() reads.
    TEST_ASSERT_EQUAL(0x03, adv.f);
    TEST_ASSERT_EQUAL(200, adv.d);  // decompressed total_size
    TEST_ASSERT_EQUAL(100, adv.t);  // compressed transfer size
}

