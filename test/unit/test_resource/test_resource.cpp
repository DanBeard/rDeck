// ============================================================
// End-to-end assembly simulation (no link/packet needed)
// ============================================================

void test_end_to_end_assembly_simulation(void) {
    // Simulate the full receive flow without a real Link:
    // 1. Parse advertisement
    // 2. Compute total_parts
    // 3. Match part against hashmap
    // 4. Assemble (concatenate, strip nonce, verify hash)
    // 5. Compute proof

    // Step 1: Parse
    Bytes adv_data(packed_advertisement, packed_advertisement_len);
    ResourceAdvertisement adv = ResourceAdvertisement::unpack(adv_data);

    // Step 2: Compute parts
    uint16_t sdu = Type::Resource::SDU;
    uint16_t total_parts = (uint16_t)std::ceil((float)adv.t / (float)sdu);
    TEST_ASSERT_EQUAL(1, total_parts);

    // Step 3: Populate hashmap from advertisement
    std::vector<Bytes> hashmap(total_parts);
    uint16_t hashes = adv.m.size() / Type::Resource::MAPHASH_LEN;
    for (uint16_t i = 0; i < hashes && i < total_parts; i++) {
        hashmap[i] = adv.m.mid(i * Type::Resource::MAPHASH_LEN, Type::Resource::MAPHASH_LEN);
    }
    TEST_ASSERT_TRUE(hashmap[0]);

    // Step 4: "Receive" the part and match it
    Bytes part_data(transfer_data, transfer_data_len);

    // Compute map hash for received part
    Bytes map_hash_input;
    map_hash_input.append(part_data);
    map_hash_input.append(adv.r);
    Bytes computed_map_hash = Identity::full_hash(map_hash_input).left(Type::Resource::MAPHASH_LEN);

    // Should match hashmap[0]
    TEST_ASSERT_TRUE(computed_map_hash == hashmap[0]);

    // Step 5: Assemble
    Bytes stream = part_data;  // single part
    Bytes assembled = stream.mid(Type::Resource::RANDOM_HASH_SIZE);
    TEST_ASSERT_EQUAL(27, assembled.size());

    // Verify hash
    Bytes verify_input;
    verify_input.append(assembled);
    verify_input.append(adv.r);
    Bytes calculated_hash = Identity::full_hash(verify_input);
    TEST_ASSERT_TRUE(calculated_hash == adv.h);

    // Step 6: Compute proof
    Bytes proof_input;
    proof_input.append(assembled);
    proof_input.append(adv.h);
    Bytes proof = Identity::full_hash(proof_input);
    TEST_ASSERT_TRUE(proof == Bytes(expected_proof_bytes, 32));
}


