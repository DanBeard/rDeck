// ============================================================
// Assembly hash verification logic
// ============================================================

void test_assembly_hash_verification_logic(void) {
    // Simulate the assembly verification:
    // 1. Concatenate parts (for single part: just the transfer_data)
    // 2. Strip nonce (first RANDOM_HASH_SIZE bytes)
    // 3. Verify SHA256(stripped_data + random_hash) == resource_hash

    Bytes stream(transfer_data, transfer_data_len);

    // Strip nonce
    Bytes data = stream.mid(Type::Resource::RANDOM_HASH_SIZE);
    TEST_ASSERT_EQUAL(original_data_len, data.size());

    // Verify the stripped data matches original
    Bytes expected_data(original_data, original_data_len);
    TEST_ASSERT_TRUE(data == expected_data);

    // Verify hash
    Bytes hash_input;
    hash_input.append(data);
    hash_input.append(Bytes(random_hash_bytes, 4));
    Bytes calculated_hash = Identity::full_hash(hash_input);

    Bytes expected_hash(resource_hash_bytes, 32);
    TEST_ASSERT_TRUE(calculated_hash == expected_hash);
}

void test_assembly_hash_verification_fails_on_corruption(void) {
    // Flip a byte in the transfer data
    uint8_t corrupted[transfer_data_len];
    memcpy(corrupted, transfer_data, transfer_data_len);
    corrupted[10] ^= 0xFF;  // corrupt a byte

    Bytes stream(corrupted, transfer_data_len);
    Bytes data = stream.mid(Type::Resource::RANDOM_HASH_SIZE);

    Bytes hash_input;
    hash_input.append(data);
    hash_input.append(Bytes(random_hash_bytes, 4));
    Bytes calculated_hash = Identity::full_hash(hash_input);

    Bytes expected_hash(resource_hash_bytes, 32);
    TEST_ASSERT_FALSE(calculated_hash == expected_hash);
}


// ============================================================
// Proof generation logic
// ============================================================

void test_proof_generation_logic(void) {
    // proof = SHA256(assembled_data + resource_hash)
    Bytes data(original_data, original_data_len);
    Bytes hash(resource_hash_bytes, 32);

    Bytes proof_input;
    proof_input.append(data);
    proof_input.append(hash);
    Bytes proof = Identity::full_hash(proof_input);

    // proof_packet_data = resource_hash + proof
    Bytes proof_data;
    proof_data.append(hash);
    proof_data.append(proof);

    TEST_ASSERT_EQUAL(64, proof_data.size());

    // First 32 bytes should be resource hash
    TEST_ASSERT_TRUE(proof_data.left(32) == hash);

    // Last 32 bytes should be the proof
    Bytes expected_proof(expected_proof_bytes, 32);
    TEST_ASSERT_TRUE(proof_data.mid(32) == expected_proof);
}


// ============================================================
// Request-next packet format
// ============================================================

void test_request_packet_format_not_exhausted(void) {
    // Request packet: [0x00][resource_hash (32 bytes)][part_hashes...]
    // When hashmap is NOT exhausted, first byte is 0x00
    Bytes request_data;
    request_data.append((uint8_t)Type::Resource::HASHMAP_IS_NOT_EXHAUSTED);
    request_data.append(Bytes(resource_hash_bytes, 32));
    request_data.append(Bytes(map_hash_part0, 4));

    TEST_ASSERT_EQUAL(37, request_data.size());
    TEST_ASSERT_EQUAL(0x00, request_data.data()[0]);
    // resource hash starts at byte 1
    TEST_ASSERT_TRUE(request_data.mid(1, 32) == Bytes(resource_hash_bytes, 32));
    // part hash at byte 33
    TEST_ASSERT_TRUE(request_data.mid(33, 4) == Bytes(map_hash_part0, 4));
}

void test_request_packet_format_exhausted(void) {
    // When hashmap IS exhausted:
    // [0xFF][last_map_hash (4 bytes)][resource_hash (32 bytes)][part_hashes...]
    Bytes request_data;
    request_data.append((uint8_t)Type::Resource::HASHMAP_IS_EXHAUSTED);
    request_data.append(Bytes(map_hash_part0, 4));  // last known hash
    request_data.append(Bytes(resource_hash_bytes, 32));

    TEST_ASSERT_EQUAL(37, request_data.size());
    TEST_ASSERT_EQUAL(0xFF, request_data.data()[0]);
    // last map hash at byte 1
    TEST_ASSERT_TRUE(request_data.mid(1, 4) == Bytes(map_hash_part0, 4));
    // resource hash at byte 5
    TEST_ASSERT_TRUE(request_data.mid(5, 32) == Bytes(resource_hash_bytes, 32));
}


