void test_adv_unpack_flags_decoding(void) {
    // Build a custom advertisement with flags = 0x13 (encrypted + compressed + is_response)
    // f = 0x13 = 0b00010011 → e=1, c=1, s=0, u=0, p=1
    JsonDocument doc;
    doc["t"] = 100;
    doc["d"] = 80;
    doc["n"] = 1;
    doc["h"] = MsgPackBinary(resource_hash_bytes, 32);
    doc["r"] = MsgPackBinary(random_hash_bytes, 4);
    doc["o"] = MsgPackBinary(resource_hash_bytes, 32);
    doc["i"] = 1;
    doc["l"] = 1;
    doc["q"] = MsgPackBinary(random_hash_bytes, 4); // non-null request_id
    doc["f"] = 0x13;
    doc["m"] = MsgPackBinary(map_hash_part0, 4);

    uint8_t buffer[256];
    size_t len = serializeMsgPack(doc, buffer, sizeof(buffer));
    Bytes packed(buffer, len);

    ResourceAdvertisement adv = ResourceAdvertisement::unpack(packed);

    TEST_ASSERT_TRUE(adv.e);   // bit 0
    TEST_ASSERT_TRUE(adv.c);   // bit 1
    TEST_ASSERT_FALSE(adv.s);  // bit 2
    TEST_ASSERT_FALSE(adv.u);  // bit 3
    TEST_ASSERT_TRUE(adv.p);   // bit 4
    TEST_ASSERT_FALSE(adv.x);  // bit 5
    TEST_ASSERT_EQUAL(0x13, adv.f);

    // request_id should be set
    TEST_ASSERT_TRUE(adv.q);
    TEST_ASSERT_EQUAL(4, adv.q.size());
}

void test_adv_unpack_invalid_data_returns_defaults(void) {
    // ArduinoJson's deserializeMsgPack is lenient — many byte sequences parse
    // without error. Rather than relying on exceptions, verify that a garbage
    // advertisement has zero-valued fields (no valid resource hash, etc.)
    uint8_t garbage[] = {0xC1};  // msgpack "never used" type → parse error
    Bytes garbage_bytes(garbage, 1);
    bool threw = false;
    try {
        ResourceAdvertisement adv = ResourceAdvertisement::unpack(garbage_bytes);
    } catch (std::exception& e) {
        threw = true;
    }
    TEST_ASSERT_TRUE(threw);
}


