// Helper: build a ResourceAdvertisement with custom parameters, pack it
static Bytes build_test_advertisement(
    size_t transfer_size, size_t data_size, uint16_t num_parts,
    const Bytes& hash, const Bytes& random_hash, const Bytes& hashmap,
    uint8_t flags = 0x00
) {
    JsonDocument doc;
    doc["t"] = transfer_size;
    doc["d"] = data_size;
    doc["n"] = num_parts;
    doc["h"] = MsgPackBinary(hash.data(), hash.size());
    doc["r"] = MsgPackBinary(random_hash.data(), random_hash.size());
    doc["o"] = MsgPackBinary(hash.data(), hash.size());
    doc["i"] = 1;
    doc["l"] = 1;
    doc["q"] = nullptr;
    doc["f"] = flags;
    doc["m"] = MsgPackBinary(hashmap.data(), hashmap.size());

    uint8_t buffer[512];
    size_t len = serializeMsgPack(doc, buffer, sizeof(buffer));
    return Bytes(buffer, len);
}

void test_adv_unpack_roundtrip(void) {
    Bytes hash(resource_hash_bytes, 32);
    Bytes rh(random_hash_bytes, 4);
    Bytes hm(map_hash_part0, 4);

    Bytes packed = build_test_advertisement(31, 27, 1, hash, rh, hm);
    ResourceAdvertisement adv = ResourceAdvertisement::unpack(packed);

    TEST_ASSERT_EQUAL(31, adv.t);
    TEST_ASSERT_EQUAL(27, adv.d);
    TEST_ASSERT_EQUAL(1, adv.n);
    TEST_ASSERT_TRUE(adv.h == hash);
    TEST_ASSERT_TRUE(adv.r == rh);
    TEST_ASSERT_TRUE(adv.m == hm);
}


